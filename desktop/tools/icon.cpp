// ff-icon: draws FileFlow's icon -- the light grid on a dark tile -- at every size the desktop
// platforms ask for, as PNGs, plus a Windows .ico of them. Run by the build; no image library,
// no checked-in binaries.
//
//   ff-icon ICONSET_DIR ICO_PATH PNG_PATH
//
// writes ICONSET_DIR/icon_16x16.png ... icon_512x512@2x.png (for macOS's iconutil), a .ico holding
// 16–256 px images, and one 512 px PNG (for Linux).
// ff-icon --brand-assets REPO_ROOT also exports the shared SVG and Android vectors.
#include "../src/icon_art.h"

#include <array>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <iomanip>
#include <locale>
#include <sstream>
#include <string>
#include <vector>

namespace {

using fileflow::desktop::icon::Draw;

std::string RoundedPath(float cx, float cy, float hw, float hh, float r) {
    std::ostringstream p;
    p.imbue(std::locale::classic());
    p << std::fixed << std::setprecision(3);
    p << "M" << cx - hw + r << "," << cy - hh
      << "h" << 2 * (hw - r) << "a" << r << "," << r << " 0 0 1 " << r << "," << r
      << "v" << 2 * (hh - r) << "a" << r << "," << r << " 0 0 1 " << -r << "," << r
      << "h" << -2 * (hw - r) << "a" << r << "," << r << " 0 0 1 " << -r << "," << -r
      << "v" << -2 * (hh - r) << "a" << r << "," << r << " 0 0 1 " << r << "," << -r << "z";
    return p.str();
}

// Explicit export, never a side effect of a desktop build. Checked-in Android vectors remain
// buildable without a host C++ compiler; run this after changing icon_art.h.
bool ExportBrand(const std::filesystem::path& root) {
    std::filesystem::create_directories(root / "assets");
    const auto drawable = root / "app/src/main/res/drawable";
    std::filesystem::create_directories(drawable);
    std::ofstream svg(root / "assets/fileflow-icon.svg");
    std::ofstream foreground(drawable / "ic_launcher_foreground.xml");
    std::ofstream mono(drawable / "ic_launcher_monochrome.xml");
    svg.imbue(std::locale::classic());
    foreground.imbue(std::locale::classic());
    mono.imbue(std::locale::classic());
    svg << "<!-- Generated by ff-icon; source: desktop/src/icon_art.h -->\n"
           "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 1024 1024\">\n"
           "  <defs><linearGradient id=\"tile\" x2=\"0\" y2=\"1\">"
           "<stop stop-color=\"#0d2e38\"/><stop offset=\"1\" stop-color=\"#0a1a1f\"/>"
           "</linearGradient></defs>\n"
           "  <rect x=\"100\" y=\"100\" width=\"824\" height=\"824\" rx=\"185.4\" fill=\"url(#tile)\"/>\n";
    for (std::ostream* out : {&foreground, &mono}) {
        *out << "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
                "<!-- Generated by ff-icon; source: desktop/src/icon_art.h.\n"
                "     All foreground artwork fits inside the central 66dp safe circle. -->\n"
                "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"\n"
                "    android:width=\"108dp\" android:height=\"108dp\""
                " android:viewportWidth=\"108\" android:viewportHeight=\"108\">\n"
                "  <group android:scaleX=\"0.075\" android:scaleY=\"0.075\""
                " android:translateX=\"15.6\" android:translateY=\"15.6\">\n";
    }
    for (const auto& sh : fileflow::desktop::icon::Shapes()) {
        std::string path = RoundedPath(sh.cx, sh.cy, sh.hw, sh.hh, sh.r);
        if (sh.hole > 0) path += " " + RoundedPath(sh.cx, sh.cy, sh.hole, sh.hole, sh.hole_radius);
        char colour[8];
        std::snprintf(colour, sizeof colour, "#%02X%02X%02X",
                      static_cast<unsigned>(std::lround(sh.colour.r * 255)),
                      static_cast<unsigned>(std::lround(sh.colour.g * 255)),
                      static_cast<unsigned>(std::lround(sh.colour.b * 255)));
        svg << "  <path fill=\"" << colour << "\" opacity=\"" << sh.colour.a
            << "\" fill-rule=\"evenodd\" d=\"" << path << "\"/>\n";
        foreground << "    <path android:fillColor=\"" << colour << "\" android:fillAlpha=\"" << sh.colour.a
                   << "\" android:fillType=\"evenOdd\" android:pathData=\"" << path << "\"/>\n";
        // Themed icons use an opaque silhouette, with real holes in the markers.
        mono << "    <path android:fillColor=\"#FFFFFF\" android:fillType=\"evenOdd\" android:pathData=\""
             << path << "\"/>\n";
    }
    svg << "</svg>\n";
    foreground << "  </group>\n</vector>\n";
    mono << "  </group>\n</vector>\n";
    svg.close();
    foreground.close();
    mono.close();
    return svg && foreground && mono;
}

std::uint32_t Crc(const std::uint8_t* p, std::size_t n, std::uint32_t crc = 0) {
    static std::array<std::uint32_t, 256> table = [] {
        std::array<std::uint32_t, 256> t{};
        for (std::uint32_t i = 0; i < 256; ++i) {
            std::uint32_t c = i;
            for (int k = 0; k < 8; ++k) c = (c & 1U) != 0 ? 0xEDB88320U ^ (c >> 1) : c >> 1;
            t[i] = c;
        }
        return t;
    }();
    crc = ~crc;
    for (std::size_t i = 0; i < n; ++i) crc = table[(crc ^ p[i]) & 0xFFU] ^ (crc >> 8);
    return ~crc;
}

void Put32(std::vector<std::uint8_t>& v, std::uint32_t x) {
    for (int i = 3; i >= 0; --i) v.push_back(static_cast<std::uint8_t>(x >> (8 * i)));
}

// A PNG of RGBA pixels, its image data a zlib stream of stored (uncompressed) blocks: no deflate
// needed, and an icon's few kilobytes don't care.
std::vector<std::uint8_t> Png(const std::vector<std::uint8_t>& rgba, int n) {
    std::vector<std::uint8_t> raw;
    for (int y = 0; y < n; ++y) {
        raw.push_back(0);  // filter: none
        const auto row = rgba.begin() + static_cast<std::ptrdiff_t>(y) * n * 4;
        raw.insert(raw.end(), row, row + n * 4);
    }
    std::vector<std::uint8_t> z = {0x78, 0x01};
    for (std::size_t i = 0; i < raw.size(); i += 65535) {
        const auto len = static_cast<std::uint16_t>(std::min<std::size_t>(65535, raw.size() - i));
        z.push_back(i + len >= raw.size() ? 1 : 0);
        z.push_back(static_cast<std::uint8_t>(len));
        z.push_back(static_cast<std::uint8_t>(len >> 8));
        z.push_back(static_cast<std::uint8_t>(~len));
        z.push_back(static_cast<std::uint8_t>(static_cast<std::uint16_t>(~len) >> 8));
        z.insert(z.end(), raw.begin() + static_cast<std::ptrdiff_t>(i), raw.begin() + static_cast<std::ptrdiff_t>(i + len));
    }
    std::uint32_t a = 1;
    std::uint32_t b = 0;
    for (auto byte : raw) {
        a = (a + byte) % 65521;
        b = (b + a) % 65521;
    }
    Put32(z, (b << 16) | a);

    std::vector<std::uint8_t> png = {0x89, 'P', 'N', 'G', '\r', '\n', 0x1A, '\n'};
    const auto chunk = [&](const char* type, const std::vector<std::uint8_t>& data) {
        Put32(png, static_cast<std::uint32_t>(data.size()));
        std::vector<std::uint8_t> body(type, type + 4);
        body.insert(body.end(), data.begin(), data.end());
        png.insert(png.end(), body.begin(), body.end());
        Put32(png, Crc(body.data(), body.size()));
    };
    std::vector<std::uint8_t> ihdr;
    Put32(ihdr, static_cast<std::uint32_t>(n));
    Put32(ihdr, static_cast<std::uint32_t>(n));
    ihdr.insert(ihdr.end(), {8, 6, 0, 0, 0});  // 8-bit RGBA
    chunk("IHDR", ihdr);
    chunk("IDAT", z);
    chunk("IEND", {});
    return png;
}

bool Write(const std::filesystem::path& p, const std::vector<std::uint8_t>& bytes) {
    std::ofstream out(p, std::ios::binary);
    out.write(reinterpret_cast<const char*>(bytes.data()), static_cast<std::streamsize>(bytes.size()));
    return static_cast<bool>(out);
}

}  // namespace

int main(int argc, char** argv) {
    if (argc == 3 && std::string(argv[1]) == "--brand-assets") {
        return ExportBrand(argv[2]) ? 0 : 1;
    }
    if (argc != 4) {
        std::fprintf(stderr, "usage: ff-icon ICONSET_DIR ICO_PATH PNG_PATH\n");
        return 2;
    }
    const std::filesystem::path iconset = argv[1];
    std::filesystem::create_directories(iconset);
    bool ok = true;
    for (int size : {16, 32, 128, 256, 512}) {
        ok &= Write(iconset / ("icon_" + std::to_string(size) + "x" + std::to_string(size) + ".png"), Png(Draw(size), size));
        ok &= Write(iconset / ("icon_" + std::to_string(size) + "x" + std::to_string(size) + "@2x.png"),
                    Png(Draw(size * 2), size * 2));
    }
    // .ico: a directory of PNG images (Windows Vista and later read PNG entries).
    std::vector<std::vector<std::uint8_t>> images;
    const int sizes[] = {16, 20, 24, 32, 40, 48, 64, 96, 128, 256};
    for (int s : sizes) images.push_back(Png(Draw(s), s));
    std::vector<std::uint8_t> ico = {0, 0, 1, 0, static_cast<std::uint8_t>(images.size()), 0};
    std::uint32_t offset = 6 + 16 * static_cast<std::uint32_t>(images.size());
    for (std::size_t i = 0; i < images.size(); ++i) {
        const auto side = static_cast<std::uint8_t>(sizes[i] >= 256 ? 0 : sizes[i]);
        ico.insert(ico.end(), {side, side, 0, 0, 1, 0, 32, 0});
        const auto size = static_cast<std::uint32_t>(images[i].size());
        for (int k = 0; k < 4; ++k) ico.push_back(static_cast<std::uint8_t>(size >> (8 * k)));
        for (int k = 0; k < 4; ++k) ico.push_back(static_cast<std::uint8_t>(offset >> (8 * k)));
        offset += size;
    }
    for (const auto& img : images) ico.insert(ico.end(), img.begin(), img.end());
    ok &= Write(argv[2], ico);
    ok &= Write(argv[3], Png(Draw(512), 512));
    if (!ok) std::fprintf(stderr, "ff-icon: could not write the icons\n");
    return ok ? 0 : 1;
}
